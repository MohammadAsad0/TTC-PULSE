"""Write one Athena CREATE EXTERNAL TABLE file per gold Parquet mart.

Reads the Arrow schema of each file in gold/ and maps each Arrow type to an
Athena (Trino) type. Output goes to aws/ddl/<table>.sql. The LOCATION line
keeps two placeholders, __BUCKET__ and __PREFIX__. aws/glue_athena_setup.sh
fills them in at run time.

Run from the repository root:
    python3 aws/generate_ddl.py
"""

from __future__ import annotations

from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

DATABASE = "ttc_pulse"
REPO_ROOT = Path(__file__).resolve().parents[1]
GOLD_DIR = REPO_ROOT / "gold"
DDL_DIR = Path(__file__).resolve().parent / "ddl"


def athena_type(data_type: pa.DataType) -> str:
    """Return the Athena type for one Arrow type. Raise on types with no safe mapping."""
    if pa.types.is_dictionary(data_type):
        return athena_type(data_type.value_type)
    if pa.types.is_boolean(data_type):
        return "BOOLEAN"
    if pa.types.is_int8(data_type):
        return "TINYINT"
    if pa.types.is_int16(data_type):
        return "SMALLINT"
    if pa.types.is_int32(data_type):
        return "INT"
    if pa.types.is_int64(data_type):
        return "BIGINT"
    if pa.types.is_uint8(data_type) or pa.types.is_uint16(data_type):
        return "INT"
    if pa.types.is_uint32(data_type):
        return "BIGINT"
    if pa.types.is_uint64(data_type):
        raise ValueError("uint64 has no safe Athena type; cast it before writing the mart")
    if pa.types.is_float32(data_type):
        return "FLOAT"
    if pa.types.is_float64(data_type):
        return "DOUBLE"
    if pa.types.is_decimal(data_type):
        return f"DECIMAL({data_type.precision},{data_type.scale})"
    if pa.types.is_string(data_type) or pa.types.is_large_string(data_type):
        return "STRING"
    if pa.types.is_binary(data_type) or pa.types.is_large_binary(data_type):
        return "BINARY"
    if pa.types.is_date(data_type):
        return "DATE"
    if pa.types.is_timestamp(data_type):
        return "TIMESTAMP"
    raise ValueError(f"No Athena mapping for Arrow type {data_type}")


def build_ddl(parquet_path: Path) -> str:
    """Return the CREATE EXTERNAL TABLE statement for one Parquet mart."""
    table = parquet_path.stem
    schema = pq.read_schema(parquet_path)
    columns = [f"  `{field.name}` {athena_type(field.type)}" for field in schema]
    lines = [
        f"-- Generated by aws/generate_ddl.py from gold/{parquet_path.name}. Do not edit by hand.",
        f"CREATE EXTERNAL TABLE IF NOT EXISTS `{DATABASE}`.`{table}` (",
        ",\n".join(columns),
        ")",
        "STORED AS PARQUET",
        f"LOCATION 's3://__BUCKET__/__PREFIX__/{table}/';",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parquet_files = sorted(GOLD_DIR.glob("*.parquet"))
    if len(parquet_files) != 8:
        raise SystemExit(f"Expected 8 gold Parquet marts in {GOLD_DIR}, found {len(parquet_files)}")
    DDL_DIR.mkdir(parents=True, exist_ok=True)
    for parquet_path in parquet_files:
        ddl_path = DDL_DIR / f"{parquet_path.stem}.sql"
        ddl_path.write_text(build_ddl(parquet_path), encoding="utf-8")
        print(f"wrote {ddl_path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
